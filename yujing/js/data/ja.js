function toKata(s) { return s.replace(/[ぁ-ゖ]/g, c => String.fromCharCode(c.charCodeAt(0) + 0x60)); }

function buildKana() {
  const out = [];
  ROWS.forEach((row, ri) => {
    const ks = row[0].includes(' ') ? row[0].split(' ') : [...row[0]];
    const rs = row[1].split(' ');
    ks.forEach((k, i) => out.push({ id: 'h-' + k, k, r: rs[i], set: '平假名', row: ri, hint: HINTS[k] || '' }));
  });
  ROWS.forEach((row, ri) => {
    const ks = row[0].includes(' ') ? row[0].split(' ') : [...row[0]];
    const rs = row[1].split(' ');
    ks.forEach((k, i) => { const kk = toKata(k); out.push({ id: 'k-' + kk, k: kk, r: rs[i], set: '片假名', row: ri, hint: HINTS[kk] || '' }); });
  });
  return out;
}

